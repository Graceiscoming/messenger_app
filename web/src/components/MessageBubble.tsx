import { UNSEND_WINDOW_HOURS } from '../constants'
import { useT } from '../i18n'
import type { MessageDto } from '../types/api'
import { formatTime, parseDate } from '../utils/format'
import Avatar from './Avatar'
import AuthedImage from './AuthedImage'
import { MoreIcon, ReplyIcon } from './icons'

interface Props {
  msg: MessageDto
  mine: boolean
  isGroup: boolean
  /** Same sender as the previous / next message (consecutive messages are visually grouped). */
  groupedPrev: boolean
  groupedNext: boolean
  /** Play the enter animation (only for messages that arrived after the room was opened). */
  animate: boolean
  /** Read receipt label ("Read" / "Read N") or null. Only passed for own messages. */
  readLabel: string | null
  menuOpen: boolean
  onToggleMenu: () => void
  onReply: () => void
  onUnsend: () => void
  onImageClick: (src: string) => void
  onMediaLoad: () => void
}

function withinUnsendWindow(m: MessageDto) {
  return !m.isUnsent && Date.now() - parseDate(m.createdAt).getTime() < UNSEND_WINDOW_HOURS * 3_600_000
}

function ReplyQuote({ msg }: { msg: MessageDto }) {
  const { t } = useT()
  const r = msg.replyTo
  if (!r) return null
  const text = r.isUnsent ? t('msg.unsent') : r.type === 'Image' ? t('preview.image') : r.type === 'Sticker' ? t('preview.sticker') : r.content ?? ''
  return (
    <div className="reply-quote">
      <b>{r.senderDisplayName}</b>
      <span>{text}</span>
    </div>
  )
}

export default function MessageBubble({
  msg, mine, isGroup, groupedPrev, groupedNext, animate, readLabel, menuOpen,
  onToggleMenu, onReply, onUnsend, onImageClick, onMediaLoad,
}: Props) {
  const { t } = useT()
  if (msg.type === 'System') {
    // System text is generated by the server (Thai) and is shown as-is.
    return <div className="system-msg"><span>{msg.content}</span></div>
  }

  const unsendable = mine && withinUnsendWindow(msg)
  const time = formatTime(msg.createdAt)
  const body = msg.isUnsent ? (
    <div className="bubble unsent" title={time}>{t('msg.unsent')}</div>
  ) : msg.type === 'Sticker' && msg.sticker ? (
    <img className="sticker" src={msg.sticker.imageUrl} alt={msg.sticker.code} onLoad={onMediaLoad} title={time} />
  ) : (
    <div className="bubble" title={time}>
      <ReplyQuote msg={msg} />
      {msg.type === 'Image' && msg.attachmentUrl && (
        <AuthedImage url={msg.attachmentUrl} className="msg-image" alt={t('msg.imageAlt')} onLoad={onMediaLoad} onClick={onImageClick} />
      )}
      {msg.content && <p className="msg-text">{msg.content}</p>}
    </div>
  )

  const cls = ['msg-row', mine ? 'mine' : 'theirs', groupedPrev && 'gp', groupedNext && 'gn', animate && 'anim'].filter(Boolean).join(' ')

  return (
    <div className={cls}>
      {!mine && (groupedNext
        ? <span className="avatar-spacer" />
        : <Avatar url={msg.sender.avatarUrl} name={msg.sender.displayName} size={32} />)}
      <div className="msg-col">
        {!mine && isGroup && !groupedPrev && <span className="sender-name">{msg.sender.displayName}</span>}
        <div className="msg-line">
          {mine && !groupedNext && <MetaBlock readLabel={readLabel} time={time} />}
          {body}
          {!mine && !groupedNext && <MetaBlock readLabel={null} time={time} />}
          {!msg.isUnsent && (
            <div className="menu-wrap msg-menu">
              <button className="icon-btn" aria-label={t('msg.menu')} onClick={(e) => { e.stopPropagation(); onToggleMenu() }}><MoreIcon /></button>
              {menuOpen && (
                <div className={`menu ${mine ? 'left' : ''}`}>
                  <button onClick={onReply}><ReplyIcon /> {t('msg.reply')}</button>
                  {unsendable && <button className="danger" onClick={onUnsend}>{t('msg.unsend')}</button>}
                </div>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  )
}

function MetaBlock({ readLabel, time }: { readLabel: string | null; time: string }) {
  return (
    <span className="meta">
      {readLabel && <span className="read">{readLabel}</span>}
      <span>{time}</span>
    </span>
  )
}
